/**
 * Block Browser's own start page: a search box (the chosen search engine, Google by default), blocking statistics
 * and the most visited sites.
 *
 * It's generated by the app when WebView asks for {@link #URL} (on the address Android reserves for app content),
 * so it never touches the network. It has no JavaScript bridge to the app: the only links back into the app are
 * plain navigations to {@link #STATS_URL}, which the browser intercepts. Private windows get a version without
 * shortcuts or saved statistics.
 */
final class HomePage {
  static final String ORIGIN = "https://appassets.androidplatform.net";
  static final String URL = ORIGIN + "/home";
  static final String STATS_URL = ORIGIN + "/home/statistics";
  static final String HIDE_URL = ORIGIN + "/home/hide-site?host=";
  static final String RESTORE_URL = ORIGIN + "/home/restore-sites";

  private HomePage() {}

  static boolean isHome(String url) {
    if (url == null) return false;
    String u = url;
    int q = u.indexOf('?'); if (q >= 0) u = u.substring(0, q);
    int h = u.indexOf('#'); if (h >= 0) u = u.substring(0, h);
    if (u.endsWith("/")) u = u.substring(0, u.length() - 1);
    return u.equals(URL);
  }

  static boolean isStatsLink(String url) { return url != null && url.startsWith(STATS_URL); }
  static boolean isHideLink(String url) { return url != null && url.startsWith(HIDE_URL); }
  static boolean isRestoreLink(String url) { return RESTORE_URL.equals(url); }

  /** What the page needs, gathered on a background thread (WebView's request thread). */
  static final class Data {
    boolean isPrivate;
    String engineName, searchAction, searchParam;
    long today, allTime, session;
    final List<long[]> week = new ArrayList<>();      // [dayStartMillis, count], oldest first
    final List<String> weekLabels = new ArrayList<>();
    final List<Map.Entry<String, Long>> topBlocked = new ArrayList<>();
    final List<String[]> shortcuts = new ArrayList<>(); // {url, title, iconDataUri or null}
    int blocklistSize;
    boolean hasHiddenSites;
  }

  static Data collect(MainActivity a) {
    Data d = new Data();
    d.isPrivate = a.isPrivate();
    int engine = a.engine();
    d.engineName = MainActivity.ENGINE_NAMES[engine];
    String prefix = MainActivity.ENGINE_URLS[engine]; // e.g. https://www.google.com/search?q=
    int qm = prefix.indexOf('?');
    d.searchAction = qm < 0 ? prefix : prefix.substring(0, qm);
    String param = qm < 0 ? "q" : prefix.substring(qm + 1);
    d.searchParam = param.endsWith("=") ? param.substring(0, param.length() - 1) : param;
    d.session = a.blockedCount.get();
    d.blocklistSize = a.listLoaded ? a.blocked.size() : 0;

    BlockingStats stats = a.blockingStats;
    if (stats != null) {
      stats.flush();
      d.allTime = stats.total();
      Map<String, Long> daily = stats.daily();
      SimpleDateFormat key = new SimpleDateFormat("yyyy-MM-dd", Locale.ROOT);
      SimpleDateFormat label = new SimpleDateFormat("EEE", Locale.getDefault());
      Calendar c = Calendar.getInstance();
      c.add(Calendar.DAY_OF_YEAR, -6);
      for (int i = 0; i < 7; i++) {
        String k = key.format(c.getTime());
        Long n = daily.get(k);
        d.week.add(new long[]{c.getTimeInMillis(), n == null ? 0 : n});
        d.weekLabels.add(i == 6 ? "Today" : label.format(c.getTime()));
        c.add(Calendar.DAY_OF_YEAR, 1);
      }
      d.today = d.week.get(6)[1];
      List<Map.Entry<String, Long>> ranked = new ArrayList<>(stats.topDomains().entrySet());
      Collections.sort(ranked, (x, y) -> Long.compare(y.getValue(), x.getValue()));
      for (int i = 0; i < Math.min(6, ranked.size()); i++) d.topBlocked.add(ranked.get(i));
    } else {
      d.today = d.session;
    }

    if (!d.isPrivate) {
      d.hasHiddenSites = !a.getSharedPreferences("hidden_home_sites", android.content.Context.MODE_PRIVATE).getAll().isEmpty();
      Set<String> hosts = new LinkedHashSet<>();
      for (HistoryStore.Entry e : a.history().topSites(60)) {
        if (isHome(e.url) || e.host.isEmpty()) continue;
        String host = e.host.startsWith("www.") ? e.host.substring(4) : e.host;
        if (a.getSharedPreferences("hidden_home_sites", android.content.Context.MODE_PRIVATE).getBoolean(host, false)) continue;
        if (!hosts.add(host)) continue;
        String origin = UrlTools.origin(e.url);
        String title = shortTitle(e.title, host);
        d.shortcuts.add(new String[]{origin + "/", title, iconDataUri(a.favicons().get(e.host)), host});
        if (d.shortcuts.size() >= 8) break;
      }
    }
    return d;
  }

  /** "GitHub: Let's build from here" → "GitHub"; falls back to the site name. */
  static String shortTitle(String title, String host) {
    String t = title == null ? "" : title.trim();
    for (String sep : new String[]{" - ", " | ", " – ", " — ", ": "}) {
      int i = t.indexOf(sep);
      if (i > 0) t = t.substring(0, i);
    }
    if (t.isEmpty() || t.length() > 18) {
      String h = host;
      int dot = h.lastIndexOf('.');
      int prev = dot > 0 ? h.lastIndexOf('.', dot - 1) : -1;
      t = dot > 0 ? h.substring(prev + 1, dot) : h;
      if (!t.isEmpty()) t = Character.toUpperCase(t.charAt(0)) + t.substring(1);
    }
    return t;
  }

  static String iconDataUri(Bitmap b) {
    if (b == null) return null;
    try {
      ByteArrayOutputStream out = new ByteArrayOutputStream();
      Bitmap small = b.getWidth() > 64 ? Bitmap.createScaledBitmap(b, 64, 64 * b.getHeight() / Math.max(1, b.getWidth()), true) : b;
      small.compress(Bitmap.CompressFormat.PNG, 100, out);
      return "data:image/png;base64," + Base64.encodeToString(out.toByteArray(), Base64.NO_WRAP);
    } catch (Exception e) {
      return null;
    }
  }

  static String esc(String s) {
    if (s == null) return "";
    StringBuilder b = new StringBuilder(s.length() + 16);
    for (int i = 0; i < s.length(); i++) {
      char c = s.charAt(i);
      switch (c) {
        case '&': b.append("&amp;"); break;
        case '<': b.append("&lt;"); break;
        case '>': b.append("&gt;"); break;
        case '"': b.append("&quot;"); break;
        case '\'': b.append("&#39;"); break;
        default: b.append(c);
      }
    }
    return b.toString();
  }

  static String fmt(long n) { return String.format(Locale.getDefault(), "%,d", n); }

  static WebResourceResponse response(MainActivity a) {
    String html = render(collect(a));
    WebResourceResponse r = new WebResourceResponse("text/html", "UTF-8", new ByteArrayInputStream(html.getBytes(StandardCharsets.UTF_8)));
    Map<String, String> headers = new HashMap<>();
    headers.put("Cache-Control", "no-store");
    // Only inline styles and this page's own small script; no network access at all.
    headers.put("Content-Security-Policy", "default-src 'none'; img-src data:; style-src 'unsafe-inline'; script-src 'unsafe-inline'; form-action https:; base-uri 'none'");
    r.setResponseHeaders(headers);
    r.setStatusCodeAndReasonPhrase(200, "OK");
    return r;
  }

  static String render(Data d) {
    String accent = d.isPrivate ? "#c4a8ff" : "#83b9ff";
    String bg = d.isPrivate ? "#251b38" : "#111827";
    String card = d.isPrivate ? "#33264d" : "#1b2638";
    StringBuilder h = new StringBuilder(8192);
    h.append("<!doctype html><html><head><meta charset=utf-8>")
     .append("<meta name=viewport content='width=device-width,initial-scale=1,maximum-scale=1'>")
     .append("<meta name=color-scheme content=dark>")
     .append("<title>").append(d.isPrivate ? "Private tab" : "New tab").append("</title><style>")
     .append(":root{--bg:").append(bg).append(";--card:").append(card).append(";--accent:").append(accent)
     .append(";--text:#eaf1fc;--muted:#aab8cc;--line:rgba(255,255,255,.08)}")
     .append("*{box-sizing:border-box}html,body{margin:0;background:var(--bg);color:var(--text);font-family:system-ui,-apple-system,Roboto,sans-serif}")
     .append("main{max-width:560px;margin:0 auto;padding:44px 18px 40px}")
     .append(".brand{display:flex;align-items:center;justify-content:center;gap:10px;font-size:26px;font-weight:700;letter-spacing:-.3px;margin-bottom:22px}")
     .append(".brand svg{width:34px;height:34px}")
     .append("form{display:flex;align-items:center;background:var(--card);border:1px solid var(--line);border-radius:28px;padding:0 6px 0 18px;height:56px}")
     .append("form:focus-within{border-color:var(--accent)}")
     .append("input{flex:1;min-width:0;background:none;border:0;outline:0;color:var(--text);font-size:17px;height:100%}")
     .append("input::placeholder{color:var(--muted)}")
     .append("button{width:46px;height:46px;border:0;border-radius:23px;background:var(--accent);color:#111827;font-size:20px;font-weight:700}")
     .append(".shortcuts{display:grid;grid-template-columns:repeat(4,1fr);gap:14px 8px;margin:26px 0 8px}")
     .append(".sc{display:flex;flex-direction:column;align-items:center;gap:7px;text-decoration:none;color:var(--text);font-size:12px;min-width:0}")
     .append(".sc span{max-width:100%;overflow:hidden;text-overflow:ellipsis;white-space:nowrap}")
     .append(".shortcut{position:relative;min-width:0}.remove-site{position:absolute;top:-8px;right:2px;width:25px;height:25px;border-radius:50%;background:#33435b;color:white;text-align:center;line-height:25px;text-decoration:none;font-size:17px;z-index:2}")
     .append(".ic{width:52px;height:52px;border-radius:16px;background:var(--card);display:flex;align-items:center;justify-content:center;font-weight:700;font-size:20px;color:var(--accent);overflow:hidden}")
     .append(".ic img{width:28px;height:28px}")
     .append("h2{font-size:14px;font-weight:700;color:var(--accent);margin:28px 4px 10px;text-transform:none}")
     .append(".stats{display:grid;grid-template-columns:repeat(3,1fr);gap:10px}")
     .append(".st{background:var(--card);border-radius:18px;padding:14px 12px}")
     .append(".st b{display:block;font-size:24px;font-weight:700;letter-spacing:-.4px}")
     .append(".st small{color:var(--muted);font-size:12px}")
     .append(".panel{background:var(--card);border-radius:18px;padding:16px}")
     .append(".bars{display:flex;align-items:flex-end;gap:8px;height:96px}")
     .append(".bar{flex:1;display:flex;flex-direction:column;align-items:center;justify-content:flex-end;height:100%;gap:6px}")
     .append(".bar i{display:block;width:100%;border-radius:6px 6px 3px 3px;background:var(--accent);min-height:3px}")
     .append(".bar.today i{background:#60d6bb}.bar em{font-style:normal;font-size:11px;color:var(--muted)}")
     .append(".row{display:flex;align-items:center;gap:10px;padding:9px 0;border-top:1px solid var(--line);font-size:14px}")
     .append(".row:first-child{border-top:0;padding-top:0}.row .d{flex:1;min-width:0;overflow:hidden;text-overflow:ellipsis;white-space:nowrap}")
     .append(".row .n{color:var(--muted);font-variant-numeric:tabular-nums}")
     .append(".meter{height:4px;border-radius:2px;background:var(--line);margin-top:6px}.meter i{display:block;height:100%;border-radius:2px;background:var(--accent)}")
     .append(".more{display:block;text-align:center;margin-top:12px;color:var(--accent);text-decoration:none;font-weight:600;font-size:14px;padding:10px}")
     .append(".note{color:var(--muted);font-size:13px;line-height:1.5;text-align:center;margin-top:18px}")
     .append(".private{background:var(--card);border-radius:18px;padding:16px;color:var(--muted);font-size:14px;line-height:1.5;margin-top:22px}")
     .append(".private b{color:var(--text)}")
     .append("</style></head><body><main>");

    // Brand mark: shield, as in the launcher icon.
    h.append("<div class=brand><svg viewBox='0 0 24 24' aria-hidden=true><path fill='none' stroke='").append(accent)
     .append("' stroke-width='2' stroke-linejoin='round' d='M12 2.5c3.2 1.9 6.2 2.4 8 2.6l-.4 7.4c-.4 4.1-3.4 7.1-7.6 9-4.2-1.9-7.2-4.9-7.6-9L4 5.1c1.8-.2 4.8-.7 8-2.6z'/>")
     .append("<circle cx=12 cy=12 r=4.2 fill='none' stroke='").append(accent).append("' stroke-width='1.6'/></svg>")
     .append(d.isPrivate ? "Private" : "Block Browser").append("</div>");

    // Search: a normal form to the chosen engine; addresses go straight to the site.
    h.append("<form id=f action='").append(esc(d.searchAction)).append("' method=get role=search>")
     .append("<input id=q name='").append(esc(d.searchParam)).append("' type=search autocomplete=off autocapitalize=off spellcheck=false enterkeyhint=go ")
     .append("placeholder='Search ").append(esc(d.engineName)).append(" or type a URL' aria-label='Search ").append(esc(d.engineName)).append(" or type a URL'>")
     .append("<button aria-label=Search>&#8594;</button></form>");
    h.append("<script>document.getElementById('f').addEventListener('submit',function(e){var v=document.getElementById('q').value.trim();")
     .append("if(!v){e.preventDefault();return;}")
     .append("if(/^https?:\\/\\/\\S+$/i.test(v)){e.preventDefault();location.href=v;return;}")
     .append("if(!/\\s/.test(v)&&/^[a-z0-9-]+(\\.[a-z0-9-]+)*\\.[a-z]{2,}(:\\d+)?(\\/\\S*)?$/i.test(v)){e.preventDefault();location.href='https://'+v;}});</script>");

    if (!d.shortcuts.isEmpty()) {
      h.append("<nav class=shortcuts aria-label='Most visited'>");
      for (String[] s : d.shortcuts) {
        h.append("<div class=shortcut><a class=sc href='").append(esc(s[0])).append("'><div class=ic>");
        if (s[2] != null) h.append("<img alt='' src='").append(s[2]).append("'>");
        else h.append(esc(s[1].isEmpty() ? "?" : s[1].substring(0, 1).toUpperCase(Locale.ROOT)));
        h.append("</div><span>").append(esc(s[1])).append("</span></a>")
         .append("<a class=remove-site aria-label='Remove suggested website' href='").append(HIDE_URL)
         .append(esc(s[3])).append("'>&times;</a></div>");
      }
      h.append("</nav>");
    }
    if (!d.isPrivate && d.hasHiddenSites) h.append("<a class=more href='").append(RESTORE_URL).append("'>Restore hidden suggested sites</a>");

    // Blocking statistics
    h.append("<h2>Ads and trackers blocked</h2><div class=stats>")
     .append("<div class=st><b>").append(fmt(d.today)).append("</b><small>Today</small></div>")
     .append("<div class=st><b>").append(fmt(d.session)).append("</b><small>This session</small></div>")
     .append("<div class=st><b>").append(d.isPrivate ? "—" : fmt(d.allTime)).append("</b><small>").append(d.isPrivate ? "Not saved" : "All time").append("</small></div>")
     .append("</div>");

    if (!d.isPrivate && !d.week.isEmpty()) {
      long max = 1;
      for (long[] w : d.week) max = Math.max(max, w[1]);
      h.append("<h2>Last 7 days</h2><div class=panel><div class=bars role=img aria-label='Blocked requests per day for the last 7 days'>");
      for (int i = 0; i < d.week.size(); i++) {
        long n = d.week.get(i)[1];
        int pct = (int) Math.max(3, Math.round(100.0 * n / max));
        h.append("<div class='bar").append(i == 6 ? " today" : "").append("' title='").append(fmt(n)).append("'><i style='height:").append(pct)
         .append("%'></i><em>").append(esc(d.weekLabels.get(i))).append("</em></div>");
      }
      h.append("</div></div>");
    }

    if (!d.topBlocked.isEmpty()) {
      long top = Math.max(1, d.topBlocked.get(0).getValue());
      h.append("<h2>Most blocked</h2><div class=panel>");
      for (Map.Entry<String, Long> e : d.topBlocked) {
        int pct = (int) Math.max(4, Math.round(100.0 * e.getValue() / top));
        h.append("<div class=row><div class=d>").append(esc(e.getKey())).append("<div class=meter><i style='width:").append(pct)
         .append("%'></i></div></div><span class=n>").append(fmt(e.getValue())).append("</span></div>");
      }
      h.append("</div>");
    }
    h.append("<a class=more href='").append(STATS_URL).append("'>All blocking statistics</a>");

    if (d.isPrivate) {
      h.append("<div class=private><b>You're browsing privately.</b> Pages you visit here aren't saved to history, and their cookies and site data ")
       .append("are deleted when you close the last private window. Downloads are kept. Websites and your network can still see what you visit.</div>");
    } else if (d.allTime == 0 && d.session == 0) {
      h.append("<p class=note>Browse as usual: ads and trackers Block Browser stops will be counted here.</p>");
    }
    if (d.blocklistSize > 0) h.append("<p class=note>Protecting against ").append(fmt(d.blocklistSize)).append(" known ad, tracker and malware domains.</p>");
    h.append("</main></body></html>");
    return h.toString();
  }
}
