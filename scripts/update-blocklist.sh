#!/usr/bin/env bash
# Downloads the StevenBlack unified hosts list (ads + malware, MIT licence)
# and writes it as one domain per line to app/src/main/assets/blocklist.txt.
# Run from the repo root. CI runs this before every build so releases get the latest list.
set -euo pipefail

SOURCE_URL="https://raw.githubusercontent.com/StevenBlack/hosts/master/hosts"
OUT="app/src/main/assets/blocklist.txt"
TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT

curl -fsSL --retry 3 "$SOURCE_URL" -o "$TMP"

SOURCE_DATE="$(grep -m1 '^# Date:' "$TMP" | sed 's/^# Date: //' || true)"

DOMAINS="$(awk '$1=="0.0.0.0" && $2!="0.0.0.0" {print tolower($2)}' "$TMP" | sort -u)"
COUNT="$(printf '%s\n' "$DOMAINS" | grep -c . || true)"

# Sanity check: refuse to replace the list with something broken or truncated.
if [ "$COUNT" -lt 10000 ]; then
  echo "Only $COUNT domains parsed from $SOURCE_URL - refusing to overwrite $OUT" >&2
  exit 1
fi

mkdir -p "$(dirname "$OUT")"
{
  echo "# Block Browser ad/tracker blocklist - generated by scripts/update-blocklist.sh"
  echo "# Source: StevenBlack unified hosts (https://github.com/StevenBlack/hosts), MIT licence"
  echo "# Source date: ${SOURCE_DATE:-unknown}"
  echo "# Domains: $COUNT"
  printf '%s\n' "$DOMAINS"
} > "$OUT"

echo "Wrote $COUNT domains to $OUT"
