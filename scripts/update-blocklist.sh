#!/usr/bin/env bash
# Builds app/src/main/assets/blocklist.txt (one domain per line) from two sources:
#   1. StevenBlack unified hosts (ads + malware)          - MIT licence
#   2. HaGeZi Multi PRO, domains-only format              - GPL-3.0 licence
# Subdomains of an already-listed domain are dropped, because the app blocks
# every subdomain of a listed domain anyway.
# Run from the repo root. Needs curl and python3. CI runs this before every build.
set -euo pipefail

STEVENBLACK_URL="https://raw.githubusercontent.com/StevenBlack/hosts/master/hosts"
HAGEZI_URL="https://raw.githubusercontent.com/hagezi/dns-blocklists/main/wildcard/pro-onlydomains.txt"
OUT="app/src/main/assets/blocklist.txt"
TMPDIR_="$(mktemp -d)"
trap 'rm -rf "$TMPDIR_"' EXIT

curl -fsSL --retry 3 "$STEVENBLACK_URL" -o "$TMPDIR_/stevenblack"
curl -fsSL --retry 3 "$HAGEZI_URL" -o "$TMPDIR_/hagezi"

mkdir -p "$(dirname "$OUT")"
python3 - "$TMPDIR_/stevenblack" "$TMPDIR_/hagezi" "$OUT" <<'PY'
import re, sys
sb_path, hz_path, out_path = sys.argv[1:4]
valid = re.compile(r"^[a-z0-9_]([a-z0-9_-]*[a-z0-9_])?(\.[a-z0-9_]([a-z0-9_-]*[a-z0-9_])?)+$")

def header_value(path, key):
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            if line.startswith("#") and key in line:
                return line.split(":", 1)[1].strip()
    return "unknown"

sb = set()
with open(sb_path, encoding="utf-8", errors="replace") as f:
    for line in f:
        parts = line.split()
        if len(parts) >= 2 and parts[0] == "0.0.0.0" and parts[1] != "0.0.0.0":
            sb.add(parts[1].lower())

hz = set()
with open(hz_path, encoding="utf-8", errors="replace") as f:
    for line in f:
        line = line.strip().lower()
        if line and not line.startswith("#"):
            hz.add(line)

# Refuse to write a broken list if a download was truncated or the format changed.
if len(sb) < 10000 or len(hz) < 50000:
    sys.exit(f"Parsed only {len(sb)} StevenBlack / {len(hz)} HaGeZi domains - refusing to overwrite {out_path}")

merged = {d for d in sb | hz if valid.match(d)}

def has_listed_parent(d):
    while "." in d:
        d = d.split(".", 1)[1]
        if d in merged:
            return True
    return False

final = sorted(d for d in merged if not has_listed_parent(d))

with open(out_path, "w", encoding="utf-8") as f:
    f.write("# Block Browser ad/tracker blocklist - generated by scripts/update-blocklist.sh\n")
    f.write("# Sources:\n")
    f.write(f"#   StevenBlack unified hosts (https://github.com/StevenBlack/hosts), MIT licence, {header_value(sb_path, 'Date:')}\n")
    f.write(f"#   HaGeZi Multi PRO (https://github.com/hagezi/dns-blocklists), GPL-3.0 licence, version {header_value(hz_path, 'Version:')}\n")
    f.write(f"# Domains: {len(final)} (each also blocks its subdomains)\n")
    f.write("\n".join(final) + "\n")

print(f"StevenBlack {len(sb)} + HaGeZi {len(hz)} -> {len(final)} domains written to {out_path}")
PY
